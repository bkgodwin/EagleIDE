/* Optional Playwright integration check against external_tools_browser_fixture.py only. */
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const base = process.env.EAGLE_TOOL_TEST_URL;
if (!base || !/^http:\/\/127\.0\.0\.1:\d+$/.test(base)) throw new Error('Set EAGLE_TOOL_TEST_URL to the isolated local fixture URL');

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.EAGLE_TOOL_BROWSER || chromium.executablePath() });
  try {
    async function account(payload) {
      const context = await browser.newContext({ viewport: { width: 1365, height: 900 } });
      await context.addInitScript(value => { try { sessionStorage.setItem('eagle-auth-session-v1', JSON.stringify(value)); } catch {} }, payload);
      const page = await context.newPage();
      page.on('dialog', dialog => dialog.accept());
      await page.goto(base, { waitUntil: 'domcontentloaded', timeout: 90000 });
      await page.waitForFunction(() => window.ExternalTools && window.EagleIDE?.getContext?.());
      return { context, page };
    }
    const { context, page } = await account({ adminToken: 'fixture-admin' });
    await page.locator('#roleMenuBtn').click();
    await page.locator('#adminSettingsBtn').click();
    await page.locator('[data-admin-settings-section="tools"]').click();
    await page.locator('#settingsExternalToolsBtn').click();
    await page.locator('#externalToolsEnabled').check();
    await page.locator('#externalToolsAllowed').fill('10.231.24.0/24');
    await page.locator('#externalToolsDenied').fill('10.231.24.1/32');
    await page.locator('#externalToolsPolicySave').click();
    await page.locator('#externalToolsAdminStatus').filter({ hasText: 'Policy saved' }).waitFor();
    await page.locator('#externalToolName').fill('Generic fixture');
    await page.locator('#externalToolLabel').fill('Open fixture');
    await page.locator('#externalToolBackend').fill('http://fixture.internal:8080/prefix/');
    await page.locator('#externalToolSlug').fill('/fixture/');
    await page.locator('#externalToolHttp').check();
    await page.getByRole('button', { name: 'Save disabled tool', exact: true }).click();
    await page.getByRole('button', { name: 'Test connection', exact: true }).click();
    await page.locator('#externalToolsCatalog').filter({ hasText: 'Reachable' }).waitFor();
    await page.screenshot({ path: process.env.EAGLE_TOOL_SCREENSHOT_DIR + '/tools-admin-desktop.png' });
    await page.getByRole('button', { name: 'Private preview', exact: true }).click();
    const fixture = page.frameLocator('#externalToolFrameHost iframe');
    await fixture.locator('#result').filter({ hasText: '"worker":"blocked"' }).waitFor({ timeout: 30000 });
    const checks = JSON.parse(await fixture.locator('#result').textContent());
    assert.deepEqual(checks, { module: 'loaded', wasm: true, font: true, write: 'fixture write', storage: 'blocked', parent: 'blocked', worker: 'blocked' });
    assert.equal(await page.locator('#outer').isVisible(), false);
    assert.equal(await page.locator('#externalToolWorkspace').isVisible(), true);
    const frameUrl = await page.locator('#externalToolFrameHost iframe').getAttribute('src');
    const direct = await context.newPage();
    await direct.goto(base + frameUrl);
    assert.equal(await direct.evaluate(() => { try { sessionStorage.getItem('eagle-auth-session-v1'); return 'UNSAFE'; } catch { return 'blocked'; } }), 'blocked');
    await direct.close();
    await page.screenshot({ path: process.env.EAGLE_TOOL_SCREENSHOT_DIR + '/tools-preview-desktop.png' });
    assert.equal(await page.locator('#wikiViewBtn').isVisible(), true);
    assert.equal(await page.locator('#ideViewBtn').isVisible(), true);
    await page.evaluate(() => document.getElementById('themeToggleBtn').click());
    await page.screenshot({ path: process.env.EAGLE_TOOL_SCREENSHOT_DIR + '/tools-preview-light.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: process.env.EAGLE_TOOL_SCREENSHOT_DIR + '/tools-preview-narrow.png' });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
    await page.setViewportSize({ width: 1365, height: 900 });
    await page.locator('#externalToolClose').click();
    await page.locator('#roleMenuBtn').click();
    await page.locator('#adminSettingsBtn').click();
    await page.locator('[data-admin-settings-section="tools"]').click();
    await page.locator('#settingsExternalToolsBtn').click();
    await page.getByRole('button', { name: 'Confirm compatibility and enable', exact: true }).click();
    await page.locator('#externalToolsAdminStatus').filter({ hasText: 'Tool enabled' }).waitFor();
    const catalog = await page.evaluate(async () => (await (await fetch('/api/admin/tools', { headers: { 'X-Admin-Token': 'fixture-admin' } })).json()).catalog);
    const tool = catalog.tools[0];
    const teacher = await account({ teacherToken: 'fixture-teacher', currentTeacher: { email: 'teacher@example.test', role: 'teacher' } });
    await teacher.page.locator('#roleMenuBtn').click();
    await teacher.page.locator('#teacherDashboardBtn').click();
    await teacher.page.locator('[data-view="dash-classes"]').click();
    await teacher.page.locator('.external-tool-class-settings button').first().click();
    await teacher.page.locator(`.external-tool-class-settings input[value="${tool.id}"]`).check();
    await teacher.page.getByRole('button', { name: 'Save tool access', exact: true }).click();
    await teacher.page.waitForFunction(() => document.querySelector('.external-tool-class-settings input')?.checked);
    const student = await account({ userToken: 'fixture-student', currentUser: { email: 'student@example.test', role: 'student' } });
    await student.page.locator('#ideViewBtn').click();
    await student.page.evaluate(() => window.eagleEditor.setValue("print('gateway IDE smoke')"));
    await student.page.locator('#runBtn').click();
    await student.page.locator('#output').filter({ hasText: 'gateway IDE smoke' }).waitFor({ timeout: 30000 });
    await student.page.locator('#wikiViewBtn').click();
    await student.page.locator('#externalToolButtons button').filter({ hasText: 'Open fixture' }).click();
    await student.page.frameLocator('#externalToolFrameHost iframe').locator('#result').filter({ hasText: '"parent":"blocked"' }).waitFor();
    const before = await student.page.locator('#externalToolFrameHost iframe').getAttribute('src');
    await student.page.locator('#externalToolClose').click();
    assert.equal(await student.page.evaluate(() => window.eagleEditor.getValue()), "print('gateway IDE smoke')");
    await student.page.locator('#externalToolButtons button').filter({ hasText: 'Open fixture' }).click();
    await student.page.frameLocator('#externalToolFrameHost iframe').locator('#result').filter({ hasText: '"parent":"blocked"' }).waitFor();
    const activeUrl = await student.page.locator('#externalToolFrameHost iframe').getAttribute('src');
    await student.page.locator('#roleMenuBtn').click();
    await student.page.locator('#signOutBtn').click();
    await student.page.waitForFunction(() => !document.querySelector('#externalToolFrameHost iframe'));
    const forbidden = await context.request.get(base + before);
    assert.equal(forbidden.status(), 403);
    assert.equal((await context.request.get(base + activeUrl)).status(), 403);
    console.log('PASS: admin registration/test/preview/enable, teacher grant, student launch/logout, opaque module/WASM/font fetch, storage/parent/worker denial, direct-document sandbox, desktop/narrow/light/dark layout, Python execution and editor-buffer preservation.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
