"""Regenerate reviewed wheel/hash locks using Python 3.12/3.13 Linux resolution.

Requires network access to PyPI. Review the resulting diff and run CI before
deploying it. requirements.txt remains the human-edited dependency declaration.
"""

import argparse
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path
import subprocess
import sys
import tempfile
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]


def metadata(name, version=None):
    suffix = f"/{version}" if version else ""
    with urlopen(f"https://pypi.org/pypi/{name}{suffix}/json", timeout=30) as response:
        return json.load(response)


def lock_entry(item):
    name, version = item
    release = metadata(name, version)
    hashes = sorted({file["digests"]["sha256"] for file in release["urls"]})
    if not hashes:
        raise RuntimeError(f"No release hashes for {name}=={version}")
    return f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{value}" for value in hashes) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, action="append", help="reuse a pip dry-run JSON report")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="eagle-dependency-lock-") as temporary:
        reports = args.report or []
        if not reports:
            for version, abi in (("3.12", "cp312"), ("3.13", "cp313")):
                report = Path(temporary) / f"{abi}.json"
                subprocess.run([sys.executable, "-m", "pip", "install", "--disable-pip-version-check",
                    "--dry-run", "--ignore-installed", "--only-binary=:all:", "--python-version", version,
                    "--platform", "manylinux_2_28_x86_64", "--platform", "manylinux_2_27_x86_64",
                    "--platform", "manylinux_2_17_x86_64", "--platform", "manylinux2014_x86_64",
                    "--implementation", "cp", "--abi", abi, "--abi", "abi3", "--report", str(report),
                    "-r", str(ROOT / "requirements.txt")], check=True)
                reports.append(report)
        versions = {}
        for report in reports:
            for entry in json.loads(report.read_text(encoding="utf-8"))["install"]:
                name, version = entry["metadata"]["name"], entry["metadata"]["version"]
                if name in versions and versions[name] != version:
                    raise RuntimeError(f"Resolve platform-specific version disagreement for {name}")
                versions[name] = version
        # Click uses this small pure-Python dependency on Windows. Including it
        # makes the lock usable by Windows developers without changing Linux.
        versions["colorama"] = metadata("colorama")["info"]["version"]
        with ThreadPoolExecutor(max_workers=8) as pool:
            entries = list(pool.map(lock_entry, sorted(versions.items(), key=lambda item: item[0].lower())))
        (ROOT / "requirements.lock").write_text(
            "# Generated by tools/update_dependency_locks.py; review and test before deployment.\n" + "\n".join(entries),
            encoding="utf-8", newline="\n")
        pip_version = metadata("pip")["info"]["version"]
        (ROOT / "requirements-bootstrap.lock").write_text(
            "# Pinned installer; update with tools/update_dependency_locks.py.\n" + lock_entry(("pip", pip_version)),
            encoding="utf-8", newline="\n")
        print(f"Locked {len(versions)} runtime packages and the installer.")


if __name__ == "__main__":
    main()
